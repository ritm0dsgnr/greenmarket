export type LoyaltyErrorCode = (typeof LoyaltyErrorCode)[keyof typeof LoyaltyErrorCode]

export type LoyaltyResult<T> =
  | { readonly ok: true; readonly value: T }
  | { readonly ok: false; readonly code: LoyaltyErrorCode }

export function ok<T>(value: T): LoyaltyResult<T> {
  return { ok: true, value }
}

export function fail<T>(code: LoyaltyErrorCode): LoyaltyResult<T> {
  return { ok: false, code }
}
